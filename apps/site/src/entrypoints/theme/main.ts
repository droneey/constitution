// Reads the design system's tokens, refuses a value off the grid and a pair that
// loses contrast, and writes the stylesheet the site reads.
import { readFileSync, writeFileSync } from 'node:fs';

import type { BundledTheme } from 'shiki';
import { bundledThemes } from 'shiki';
import { z } from 'zod';

import type { CodeTheme, DesignToken, DesignTokenGroup, ThemeSettings } from '#/libs/ui';
import {
  checkThemeContrast,
  collectTokens,
  emitThemeCss,
  findOffGridTokens,
  formatContrastReport,
  listContrastFailures,
  ThemeMode,
  ThemeTokenError,
} from '#/libs/ui';

const SOURCE = 'src/libs/ui/theme/theme.tokens.json';
const OUTPUT = 'src/libs/ui/theme/theme.gen.css';
const BANNER = `/* Generated by src/entrypoints/theme/main.ts from ${SOURCE}; do not edit. */`;
const REFUSED_EXIT_CODE = 1;

const isBundledTheme = (name: unknown): name is BundledTheme =>
  typeof name === 'string' && Object.hasOwn(bundledThemes, name);

const tokenSchema = z.strictObject({
  $value: z.union([
    z.strictObject({
      colorSpace: z.literal('oklch'),
      components: z.tuple([
        z.number(),
        z.number(),
        z.number(),
      ]),
    }),
    z.strictObject({
      unit: z.string(),
      value: z.number(),
    }),
    z.number(),
    z.string(),
    z.array(z.number()),
  ]),
  $description: z.string().exactOptional(),
  $extensions: z
    .strictObject({
      'dev.droneey.share': z.number().exactOptional(),
      mode: z
        .strictObject({
          dark: z.union([
            z.number(),
            z.string(),
          ]),
        })
        .exactOptional(),
    })
    .exactOptional(),
}) satisfies z.ZodType<DesignToken>;

const tokenGroupSchema: z.ZodType<DesignTokenGroup> = z.lazy(() =>
  z.record(
    z.string(),
    z.union([
      tokenSchema,
      tokenGroupSchema,
      z.string(),
    ]),
  ),
);

const settingsSchema = z.strictObject({
  grid: z.array(z.number()),
  contrast: z.array(
    z.strictObject({
      foreground: z.string(),
      background: z.string(),
      minimum: z.number(),
    }),
  ),
  code: z.strictObject({
    themes: z.record(
      z.enum(ThemeMode),
      z.custom<BundledTheme>(isBundledTheme, 'names no theme shiki bundles'),
    ),
    backgrounds: z.array(z.string()),
    minimum: z.number(),
  }),
  tailwindRadius: z.record(z.string(), z.number()),
}) satisfies z.ZodType<ThemeSettings>;

// The source's groups sit beside its own description and the settings of the theme.
const sourceSchema = z
  .strictObject({
    $description: z.string().exactOptional(),
    $extensions: z.strictObject({
      'dev.droneey.theme': settingsSchema,
    }),
  })
  .catchall(tokenGroupSchema);

const loadCodeTheme = async (name: BundledTheme): Promise<CodeTheme> => {
  const { default: registration } = await bundledThemes[name]();

  return {
    ...registration,
    tokenColors: registration.tokenColors ?? [],
  };
};

const refuse = (problems: readonly string[]): void => {
  process.stderr.write(`${SOURCE} refused:\n${problems.join('\n')}\n`);
  process.exitCode = REFUSED_EXIT_CODE;
};

/** reports every contrast, writes the stylesheet, and returns what refuses the tokens */
const buildTheme = async (source: unknown): Promise<readonly string[]> => {
  const parsed = sourceSchema.safeParse(source);

  if (!parsed.success) {
    return [
      z.prettifyError(parsed.error),
    ];
  }

  const { $extensions, ...groups } = parsed.data;
  const settings = $extensions['dev.droneey.theme'];
  const tokens = collectTokens(groups);
  const [light, dark] = await Promise.all([
    loadCodeTheme(settings.code.themes[ThemeMode.Light]),
    loadCodeTheme(settings.code.themes[ThemeMode.Dark]),
  ]);
  const checks = checkThemeContrast({
    tokens,
    settings,
    codeThemes: {
      [ThemeMode.Light]: light,
      [ThemeMode.Dark]: dark,
    },
  });

  for (const check of checks) {
    process.stdout.write(`${formatContrastReport(check)}\n`);
  }

  const failures = [
    ...listContrastFailures(checks),
    ...findOffGridTokens(tokens, settings.grid),
  ];
  const css = emitThemeCss(tokens, settings.tailwindRadius);

  if (failures.length === 0) {
    writeFileSync(
      OUTPUT,
      [
        BANNER,
        ...css,
      ].join('\n'),
    );
  }

  return failures;
};

try {
  const failures = await buildTheme(JSON.parse(readFileSync(SOURCE, 'utf8')));

  if (failures.length > 0) {
    refuse(failures);
  }
} catch (error) {
  // A source that is no JSON, or tokens that refer to none or hold the wrong kind of value.
  if (!(error instanceof SyntaxError || error instanceof ThemeTokenError)) {
    throw error;
  }

  refuse([
    error.message,
  ]);
}
